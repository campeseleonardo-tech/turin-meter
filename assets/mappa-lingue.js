  var cache = {}, regex = {}, mappe = {};
  function esc(s){ return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }
  function costruisci(l){
    var i = l === "en" ? 1 : 2, voci = V.slice().sort(function(a, b){ return b[0].length - a[0].length; }), mappa = {}, parti = [];
    voci.forEach(function(v){
      var k = v[0].toLowerCase(); if(Object.prototype.hasOwnProperty.call(mappa, k)) return;
      mappa[k] = v[i];
      var a = v[0], pre = /^[A-Za-zÀ-ÿ0-9]/.test(a) ? "(?<![A-Za-zÀ-ÿ0-9])" : "", post = /[A-Za-zÀ-ÿ0-9]$/.test(a) ? "(?![A-Za-zÀ-ÿ0-9])" : "";
      parti.push(pre + esc(a) + post);
    });
    mappe[l] = mappa; regex[l] = new RegExp(parti.join("|"), "gi");
  }
  /* il pezzo trovato ha la maiuscola iniziale come l'originale (ma i nomi tedeschi restano com'e' scritto nel dizionario) */
  function traduci(s, l){
    l = l || lang;
    if(l === "it" || !s || typeof s !== "string") return s;
    if(!regex[l]) costruisci(l);
    var m = mappe[l];
    return s.replace(regex[l], function(x){
      var r = m[x.toLowerCase()];
      if(r === undefined) return x;
      if(x.charAt(0) !== x.charAt(0).toLowerCase() && r.charAt(0) === r.charAt(0).toLowerCase()) r = r.charAt(0).toUpperCase() + r.slice(1);
      return r;
    });
  }

  var ATTR = ["title", "aria-label", "placeholder", "label"], SALTA = {SCRIPT: 1, STYLE: 1, CANVAS: 1, TITLE: 1, NOSCRIPT: 1};
  function nodoTesto(n){
    var el = n.parentNode; if(!el || SALTA[el.nodeName] || (el.closest && el.closest("datalist,[data-nt]"))) return;
    var m = memoria.get(n);
    if(!m || m.fatto !== n.nodeValue) m = {it: n.nodeValue};
    var out = lang === "it" ? m.it : traduci(m.it);
    m.fatto = out; memoria.set(n, m);
    if(n.nodeValue !== out) n.nodeValue = out;
  }
  function attributi(el){
    for(var k = 0; k < ATTR.length; k++){
      var a = ATTR[k]; if(!el.hasAttribute || !el.hasAttribute(a)) continue;
      var mm = memoria.get(el) || {}, m = mm[a], v = el.getAttribute(a);
      if(!m || m.fatto !== v) m = {it: v};
      var out = lang === "it" ? m.it : traduci(m.it);
      m.fatto = out; mm[a] = m; memoria.set(el, mm);
      if(v !== out) el.setAttribute(a, out);
    }
  }
  function albero(radice){
    if(!radice) return;
    if(radice.nodeType === 3){ nodoTesto(radice); return; }
    if(radice.nodeType !== 1 || SALTA[radice.nodeName]) return;
    attributi(radice);
    var w = document.createTreeWalker(radice, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, null), n;
    while((n = w.nextNode())){ if(n.nodeType === 3) nodoTesto(n); else if(!SALTA[n.nodeName]) attributi(n); }
  }
